// Generates src/assets/icon-line-map.js — a tiny script the DEMO loads to map each icon
// `name` to the line number of its FIRST occurrence in src/index.html, so the click-info
// panel (ae-icon5-component.tsx's iconClicked) can link straight to a working code example.
// DEMO-ONLY: it lives under src/assets (copied to www/) and is never imported by the
// published component. See GitHub issue #26.
//
// Run automatically via the `prebuild` / `prestart` npm hooks.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const html = readFileSync(join(root, 'src/index.html'), 'utf8')
const lines = html.split('\n')

// Every `name="…"` in this file belongs to an <ae-icon5-component> — confirmed by grepping
// for `name="` lines that don't also contain that tag name (only the 3 unrelated <meta>
// tags in <head> match). Requiring both substrings on the same line, rather than a full
// HTML parse, is enough and keeps this script dependency-free.
const nameAttr = /name="([a-z0-9-]+)"/
const lineMap = {}
lines.forEach((line, i) => {
  if (!line.includes('ae-icon5-component')) return
  const m = line.match(nameAttr)
  if (!m) return
  const name = m[1]
  if (!(name in lineMap)) lineMap[name] = i + 1 // 1-indexed, first occurrence only
})

const out = join(root, 'src/assets')
mkdirSync(out, { recursive: true })
writeFileSync(
  join(out, 'icon-line-map.js'),
  `/* AUTO-GENERATED by scripts/gen-icon-line-map.mjs — do not edit. Demo-only. */\n` +
  `window.AE_ICON_LINE_MAP = ${JSON.stringify(lineMap)};\n`
)
console.log(`[icon-line-map] ${Object.keys(lineMap).length} icon names mapped`)
